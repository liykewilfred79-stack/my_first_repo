from pydantic import BaseModel
from typing import List

class LineItem(BaseModel):
  description: str
  amount: float

class Invoice(BaseModel):
  vendor: str
  date: str
  total: float
  items: List[LineItem]

PROMPT = """You extract data from invoices.
Return ONLY valid JSON with keys: vendor, date, total, items
(items is a list of objects with description and amount).

Example input:
Acme Ltd, 2026-01-05. Pens x2 = 4.00, Paper = 6.00. Total 10.00

Example output:
{{"vendor": "Acme Ltd", "date": "2026-01-05", "total": 10.0,
 "items": [{{"description": "Pens x2", "amount": 4.0}},
           {{"description": "Paper", "amount": 6.0}}]}}

Now extract from this text:
{text}
"""

import google.generativeai as genai
from google.colab import userdata
from pydantic import ValidationError

genai.configure(api_key=userdata.get("GEMINI_API_KEY"))
model = genai.GenerativeModel(
    "gemini-3.8-flash",
    generation_config={"response_mime_type": "application/json"},
)

def extract(text, retries=2):
    for attempt in range(retries + 1):
        reply = model.generate_content(PROMPT.format(text=text))
        try:
            return Invoice.model_validate_json(reply.text)
        except ValidationError as e:
            print("Invalid output, retrying...", e)
    raise ValueError("Could not get valid JSON")

sample = "Bright Co, 12 March 2026. Laptop stand 25.50, Cable 4.50. Total 30.00"
result = extract(sample)
print(result.model_dump_json(indent=2))

